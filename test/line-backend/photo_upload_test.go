type photoAPI struct {
	*fakeAPI
	order             []string
	original, preview []byte
	failPreview       bool
	failOriginal      bool
}

func (f *photoAPI) UploadOBSWithSID(data []byte, sid string) (string, error) {
	if sid != "emi" {
		return "", errors.New("wrong photo SID")
	}
	f.order = append(f.order, "original")
	f.original = append([]byte(nil), data...)
	if f.failOriginal {
		return "", errors.New("PRIVATE original upload failure")
	}
	return "photo-object", nil
}

func (f *photoAPI) UploadOBSWithOIDAndSID(data []byte, oid, sid string) error {
	if oid != "photo-object__ud-preview" || sid != "emi" {
		return errors.New("wrong preview object")
	}
	f.order = append(f.order, "preview")
	f.preview = append([]byte(nil), data...)
	if f.failPreview {
		return errors.New("preview failed")
	}
	return nil
}

func (f *photoAPI) UploadOBSPlain(data []byte, oid, kind string) error {
	if kind != "image" {
		return errors.New("wrong plain photo type")
	}
	switch oid {
	case "server-id":
		f.order = append(f.order, "original")
		f.original = append([]byte(nil), data...)
		if f.failOriginal {
			return errors.New("PRIVATE original upload failure")
		}
	case "server-id/preview":
		return errors.New("plain photo preview must be generated by OBS, not uploaded")
	default:
		return errors.New("wrong plain object")
	}
	return nil
}

func TestPhotoFailureStageNeverLeaksRawDetails(t *testing.T) {
	for _, tc := range []struct {
		plain, original, preview bool
		stage                    string
	}{
		{true, true, false, "upload original (plain)"},
		{false, true, false, "upload original (encrypted)"},
		{false, false, true, "upload preview (encrypted)"},
	} {
		client, base, crypto, _ := setup(t, tc.plain)
		api := &photoAPI{fakeAPI: base, failOriginal: tc.original, failPreview: tc.preview}
		client.crypto = &fileCrypto{fakeCrypto: crypto}
		client.Session.NewClient = func(string) session.API { return api }
		_, err := client.SendFile("u-peer", Attachment{Name: "photo.png", Data: testPhoto(t, "png"), Image: true}, "")
		if err == nil {
			t.Fatal("failure acknowledged")
		}
		detail := PhotoFailureSummary(err)
		if !strings.Contains(detail, tc.stage) || strings.Contains(detail, "PRIVATE") {
			t.Fatalf("unsafe or missing stage: %s", detail)
		}
		wantSends := 0
		if tc.plain {
			wantSends = 1
		}
		if base.sends != wantSends {
			t.Fatal("photo mutation was replayed")
		}
	}
	err := photoFailure("send acknowledgement", context.DeadlineExceeded)
	if !errors.Is(err, context.DeadlineExceeded) || !strings.Contains(PhotoFailureSummary(err), "timed out") {
		t.Fatal("lost deadline classification")
	}
	if !strings.Contains(PhotoFailureSummary(photoFailure("send acknowledgement", errPhotoMessageID)), "no message ID") {
		t.Fatal("missing-ID diagnostic lost")
	}
}

func (f *photoAPI) SendMessage(seq int64, msg *line.Message) (*line.Message, error) {
	f.order = append(f.order, "send")
	return f.fakeAPI.SendMessage(seq, msg)
}

func testPhoto(t *testing.T, format string) []byte {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, 600, 300))
	img.Set(2, 3, color.RGBA{255, 0, 0, 255})
	var out bytes.Buffer
	var err error
	if format == "png" {
		err = png.Encode(&out, img)
	} else {
		err = jpeg.Encode(&out, img, nil)
	}
	if err != nil {
		t.Fatal(err)
	}
	return out.Bytes()
}

func TestPhotoSendEncryptedAndPlain(t *testing.T) {
	for _, chat := range []string{"u-peer", "c-group", "r-room"} {
		for _, plain := range []bool{false, true} {
			for _, format := range []string{"png", "jpeg"} {
				t.Run(chat+format+map[bool]string{true: "plain", false: "encrypted"}[plain], func(t *testing.T) {
					client, base, crypto, _ := setup(t, plain)
					base.group = &line.E2EEGroupSharedKey{GroupKeyID: 33, Creator: "u-self", CreatorKeyID: 11, ReceiverKeyID: 11, EncryptedSharedKey: "wrapped"}
					api := &photoAPI{fakeAPI: base}
					crypt := &fileCrypto{fakeCrypto: crypto}
					client.crypto = crypt
					client.Session.NewClient = func(string) session.API { return api }
					data := testPhoto(t, format)
					result, err := client.SendFile(chat, Attachment{Name: "photo." + format, Data: data, Image: true}, "123")
					if err != nil {
						t.Fatal(err)
					}
					if result.Encrypted == plain || base.sent.ContentType != 1 || !base.sent.HasContent ||
						base.sent.RelatedMessageID != "123" || base.sent.ContentMetadata["contentType"] != "1" {
						t.Fatalf("wrong photo message: %#v", base.sent)
					}
					var info struct {
						Width, Height, FileSize int
						Extension               string
					}
					if err := json.Unmarshal([]byte(base.sent.ContentMetadata["MEDIA_CONTENT_INFO"]), &info); err != nil ||
						info.Width != 600 || info.Height != 300 {
						t.Fatalf("wrong photo metadata: %#v, %v", info, err)
					}
					if plain {
						if strings.Join(api.order, ",") != "send,original" || !bytes.Equal(api.original, data) {
							t.Fatal("plain photo flow changed")
						}
					} else {
						if strings.Join(api.order, ",") != "original,preview,send" || crypt.contentType != 1 ||
							base.sent.ContentMetadata["SID"] != "emi" || base.sent.ContentMetadata["ENC_KM"] != "" {
							t.Fatal("incorrect encrypted photo flow")
						}
						var payload map[string]string
						if err := json.Unmarshal(crypt.payloadSent, &payload); err != nil {
							t.Fatal(err)
						}
						decoded, err := decryptFile(api.original, payload["keyMaterial"])
						if err != nil || !bytes.Equal(decoded, data) {
							t.Fatal("encrypted original corrupt")
						}
						if !bytes.Equal(api.original, api.preview) {
							t.Fatal("preview must not reuse CTR stream for different plaintext")
						}
					}
				})
			}
		}
	}
}

func TestPhotoValidationAndPreviewFailureDoNotSend(t *testing.T) {
	client, base, crypto, _ := setup(t, false)
	api := &photoAPI{fakeAPI: base, failPreview: true}
	client.crypto = &fileCrypto{fakeCrypto: crypto}
	client.Session.NewClient = func(string) session.API { return api }
	var err error
	if _, err = client.SendFile("u-peer", Attachment{Name: "fake.png", Data: []byte("not an image"), Image: true}, ""); err == nil || len(api.order) != 0 {
		t.Fatal("invalid image uploaded")
	}
	if _, err = client.SendFile("u-peer", Attachment{Name: "photo.png", Data: testPhoto(t, "png"), Image: true}, ""); err == nil || base.sent != nil || strings.Join(api.order, ",") != "original,preview" {
		t.Fatal("preview failure sent message")
	}
}
